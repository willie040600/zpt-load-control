function regionOf(name: string, lat: number): Region {
  if (EAST.has(name)) return 'east'
  if (name === '金門') return 'south'
  if (lat >= 24.45) return 'north'
  if (lat >= 23.45) return 'central'
  return 'south'
}

export const NODES: Record<string, NodeInfo> = {}
for (const [name, [lon, lat, hub]] of Object.entries(RAW)) {
  NODES[name] = { name, lon, lat, hub: !!hub, region: regionOf(name, lat) }
}

// 經緯度 → 場景座標(x 向東、z 向南)
export const SCALE = 60
const LON0 = 120.9
const LAT0 = 23.7
const COS = Math.cos((LAT0 * Math.PI) / 180)

export function project(lon: number, lat: number): [number, number] {
  return [(lon - LON0) * SCALE * COS, -(lat - LAT0) * SCALE]
}

// 資料中沒有座標的單位,放在北轉旁邊
export function nodeXZ(name: string): [number, number] {
  const n = NODES[name] ?? NODES['北轉']
  return project(n.lon, n.lat)
}

